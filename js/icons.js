export function iconSvg(name, size = 20) {
  const body = raw[name];
  if (!body) return '';
  return `<svg viewBox="0 0 24 24" width="${size}" height="${size}" ${STROKE} class="icon">${body}</svg>`;
}

export function injectIcons(root = document) {
  root.querySelectorAll('[data-icon]:not([data-icon-injected])').forEach((el) => {
    const size = Number(el.dataset.iconSize || 18);
    el.innerHTML = iconSvg(el.dataset.icon, size);
    el.setAttribute('data-icon-injected', '');
  });
}
